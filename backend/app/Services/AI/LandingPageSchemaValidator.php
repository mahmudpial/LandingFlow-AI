<?php

declare(strict_types=1);

namespace App\Services\AI;

use InvalidArgumentException;

class LandingPageSchemaValidator
{
    public const SUPPORTED_SECTIONS = [
        'hero',
        'problem_solution',
        'features',
        'benefits',
        'social_proof',
        'testimonials',
        'pricing',
        'faq',
        'cta',
        'footer',
    ];

    public const ILLUSTRATIVE_DISCLAIMER = 'Illustrative placeholder content generated by AI. Replace with your verified customer quotes, metrics, and actual pricing before commercial publication.';

    /**
     * Validate, sanitize, and normalize a landing page content schema.
     *
     * @param  array<string, mixed>  $raw
     * @return array<string, mixed>
     */
    public function validateAndNormalize(array $raw, string $fallbackBrandName = 'LandingFlow Product'): array
    {
        if (! isset($raw['sections']) || ! is_array($raw['sections'])) {
            throw new InvalidArgumentException('Landing page schema must contain a "sections" object.');
        }

        $sections = $raw['sections'];
        foreach (['hero', 'features', 'cta', 'footer'] as $requiredKey) {
            if (! isset($sections[$requiredKey]) || ! is_array($sections[$requiredKey])) {
                throw new InvalidArgumentException("Landing page schema is missing required section: {$requiredKey}.");
            }
        }

        $sectionsOrder = $raw['sections_order'] ?? self::SUPPORTED_SECTIONS;
        if (! is_array($sectionsOrder) || $sectionsOrder === []) {
            $sectionsOrder = self::SUPPORTED_SECTIONS;
        }
        // Keep only valid section keys and ensure every supported section is present in the order array
        $normalizedOrder = array_values(array_intersect($sectionsOrder, self::SUPPORTED_SECTIONS));
        foreach (self::SUPPORTED_SECTIONS as $sectionKey) {
            if (! in_array($sectionKey, $normalizedOrder, true)) {
                $normalizedOrder[] = $sectionKey;
            }
        }

        $seo = is_array($raw['seo'] ?? null) ? $raw['seo'] : [];

        return [
            'seo' => [
                'title' => $this->cleanText((string) ($seo['title'] ?? "{$fallbackBrandName} — Official Landing Page"), 160),
                'description' => $this->cleanText((string) ($seo['description'] ?? "Discover how {$fallbackBrandName} helps you achieve results faster."), 320),
                'keywords' => array_values(array_map(
                    fn ($k) => $this->cleanText((string) $k, 50),
                    array_slice(is_array($seo['keywords'] ?? null) ? $seo['keywords'] : [], 0, 12)
                )),
            ],
            'sections_order' => $normalizedOrder,
            'sections' => [
                'hero' => $this->normalizeHero($sections['hero'] ?? [], $fallbackBrandName),
                'problem_solution' => $this->normalizeProblemSolution($sections['problem_solution'] ?? []),
                'features' => $this->normalizeFeatures($sections['features'] ?? []),
                'benefits' => $this->normalizeBenefits($sections['benefits'] ?? []),
                'social_proof' => $this->normalizeSocialProof($sections['social_proof'] ?? []),
                'testimonials' => $this->normalizeTestimonials($sections['testimonials'] ?? []),
                'pricing' => $this->normalizePricing($sections['pricing'] ?? []),
                'faq' => $this->normalizeFaq($sections['faq'] ?? []),
                'cta' => $this->normalizeCta($sections['cta'] ?? []),
                'footer' => $this->normalizeFooter($sections['footer'] ?? [], $fallbackBrandName),
            ],
        ];
    }

    public function sanitizeUrl(?string $url, string $default = '#cta'): string
    {
        if ($url === null || trim($url) === '') {
            return $default;
        }

        $trimmed = trim($url);

        if (str_starts_with($trimmed, '#') || str_starts_with($trimmed, '/')) {
            return preg_replace('/[\x00-\x1F\x7F]/', '', $trimmed) ?: $default;
        }

        if (preg_match('/^(https?:\/\/|mailto:|tel:)/i', $trimmed) === 1) {
            return filter_var($trimmed, FILTER_SANITIZE_URL) ?: $default;
        }

        return $default;
    }

    public function cleanText(string $value, int $maxLength = 500): string
    {
        $stripped = strip_tags($value);
        $cleaned = preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]/u', '', $stripped) ?? '';

        return mb_substr(trim($cleaned), 0, $maxLength);
    }

    private function normalizeHero(array $hero, string $brand): array
    {
        $highlights = is_array($hero['highlights'] ?? null) ? $hero['highlights'] : [];

        return [
            'visible' => (bool) ($hero['visible'] ?? true),
            'badge' => $this->cleanText((string) ($hero['badge'] ?? 'AI-Powered Workflow'), 80),
            'headline' => $this->cleanText((string) ($hero['headline'] ?? "Accelerate growth with {$brand}"), 180),
            'subheadline' => $this->cleanText((string) ($hero['subheadline'] ?? 'Purpose-built platform designed to streamline operations and boost conversions.'), 400),
            'primary_cta_text' => $this->cleanText((string) ($hero['primary_cta_text'] ?? 'Get Started'), 60),
            'primary_cta_url' => $this->sanitizeUrl((string) ($hero['primary_cta_url'] ?? '#pricing'), '#pricing'),
            'secondary_cta_text' => $this->cleanText((string) ($hero['secondary_cta_text'] ?? 'Explore Features'), 60),
            'secondary_cta_url' => $this->sanitizeUrl((string) ($hero['secondary_cta_url'] ?? '#features'), '#features'),
            'image_url' => $this->sanitizeUrl((string) ($hero['image_url'] ?? ''), ''),
            'highlights' => array_values(array_map(
                fn ($item) => $this->cleanText((string) $item, 80),
                array_slice($highlights, 0, 5)
            )),
        ];
    }

    private function normalizeProblemSolution(array $section): array
    {
        $problems = is_array($section['problem_items'] ?? null) ? $section['problem_items'] : [];
        $solutions = is_array($section['solution_items'] ?? null) ? $section['solution_items'] : [];

        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'title' => $this->cleanText((string) ($section['title'] ?? 'From Manual Bottlenecks to Automated Clarity'), 150),
            'subtitle' => $this->cleanText((string) ($section['subtitle'] ?? 'See how we replace fragmented workflows with a unified system.'), 300),
            'problem_title' => $this->cleanText((string) ($section['problem_title'] ?? 'The Old Way'), 80),
            'problem_items' => array_values(array_map(
                fn ($i) => $this->cleanText((string) $i, 200),
                array_slice($problems, 0, 5)
            )),
            'solution_title' => $this->cleanText((string) ($section['solution_title'] ?? 'The Modern Way'), 80),
            'solution_items' => array_values(array_map(
                fn ($i) => $this->cleanText((string) $i, 200),
                array_slice($solutions, 0, 5)
            )),
        ];
    }

    private function normalizeFeatures(array $section): array
    {
        $items = is_array($section['items'] ?? null) ? $section['items'] : [];

        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'title' => $this->cleanText((string) ($section['title'] ?? 'Core Capabilities Built for Scale'), 150),
            'subtitle' => $this->cleanText((string) ($section['subtitle'] ?? 'Everything you need to launch, optimize, and grow with confidence.'), 300),
            'items' => array_values(array_map(fn ($item) => [
                'icon' => $this->cleanText((string) ($item['icon'] ?? 'Sparkles'), 40),
                'title' => $this->cleanText((string) ($item['title'] ?? 'Feature Title'), 100),
                'description' => $this->cleanText((string) ($item['description'] ?? 'Feature description.'), 280),
            ], array_slice($items, 0, 8))),
        ];
    }

    private function normalizeBenefits(array $section): array
    {
        $items = is_array($section['items'] ?? null) ? $section['items'] : [];

        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'title' => $this->cleanText((string) ($section['title'] ?? 'Why Teams Switch to Our Platform'), 150),
            'subtitle' => $this->cleanText((string) ($section['subtitle'] ?? 'Designed to deliver measurable outcomes from week one.'), 300),
            'items' => array_values(array_map(fn ($item) => [
                'title' => $this->cleanText((string) ($item['title'] ?? 'Key Benefit'), 100),
                'description' => $this->cleanText((string) ($item['description'] ?? 'Clear outcome explanation.'), 260),
                'metric_label' => $this->cleanText((string) ($item['metric_label'] ?? 'Illustrative Workflow Gain'), 60),
            ], array_slice($items, 0, 6))),
        ];
    }

    private function normalizeSocialProof(array $section): array
    {
        $logos = is_array($section['logos'] ?? null) ? $section['logos'] : ['SampleCorp', 'AcmeLabs', 'VertexFlow', 'NovaStack'];

        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'is_illustrative' => true,
            'disclaimer' => self::ILLUSTRATIVE_DISCLAIMER,
            'title' => $this->cleanText((string) ($section['title'] ?? 'Built for modern growth teams (Sample Logos — Replace with your partners)'), 160),
            'logos' => array_values(array_map(
                fn ($l) => $this->cleanText((string) $l, 60),
                array_slice($logos, 0, 6)
            )),
        ];
    }

    private function normalizeTestimonials(array $section): array
    {
        $items = is_array($section['items'] ?? null) ? $section['items'] : [];

        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'is_illustrative' => true,
            'disclaimer' => self::ILLUSTRATIVE_DISCLAIMER,
            'title' => $this->cleanText((string) ($section['title'] ?? 'What Customers Can Expect (Illustrative Examples)'), 150),
            'subtitle' => $this->cleanText((string) ($section['subtitle'] ?? 'Sample testimonial cards for layout preview — replace with real customer feedback.'), 300),
            'items' => array_values(array_map(fn ($item) => [
                'quote' => $this->cleanText((string) ($item['quote'] ?? 'Illustrative feedback placeholder describing workflow improvements.'), 320),
                'author_name' => $this->cleanText((string) ($item['author_name'] ?? 'Alex Rivera (Sample Persona)'), 80),
                'author_role' => $this->cleanText((string) ($item['author_role'] ?? 'Head of Operations'), 80),
                'company' => $this->cleanText((string) ($item['company'] ?? 'Example Organization'), 80),
                'is_illustrative' => true,
            ], array_slice($items, 0, 4))),
        ];
    }

    private function normalizePricing(array $section): array
    {
        $plans = is_array($section['plans'] ?? null) ? $section['plans'] : [];

        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'is_illustrative' => true,
            'disclaimer' => self::ILLUSTRATIVE_DISCLAIMER,
            'title' => $this->cleanText((string) ($section['title'] ?? 'Suggested Pricing Structure (Illustrative)'), 150),
            'subtitle' => $this->cleanText((string) ($section['subtitle'] ?? 'Customize these suggested tiers to match your actual commercial offer.'), 300),
            'plans' => array_values(array_map(fn ($plan) => [
                'name' => $this->cleanText((string) ($plan['name'] ?? 'Starter'), 60),
                'price' => $this->cleanText((string) ($plan['price'] ?? '$29'), 40),
                'period' => $this->cleanText((string) ($plan['period'] ?? '/month'), 40),
                'description' => $this->cleanText((string) ($plan['description'] ?? 'Ideal for early teams.'), 160),
                'features' => array_values(array_map(
                    fn ($f) => $this->cleanText((string) $f, 120),
                    array_slice(is_array($plan['features'] ?? null) ? $plan['features'] : [], 0, 8)
                )),
                'cta_text' => $this->cleanText((string) ($plan['cta_text'] ?? 'Choose Plan'), 60),
                'cta_url' => $this->sanitizeUrl((string) ($plan['cta_url'] ?? '#cta'), '#cta'),
                'is_popular' => (bool) ($plan['is_popular'] ?? false),
            ], array_slice($plans, 0, 4))),
        ];
    }

    private function normalizeFaq(array $section): array
    {
        $items = is_array($section['items'] ?? null) ? $section['items'] : [];

        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'title' => $this->cleanText((string) ($section['title'] ?? 'Frequently Asked Questions'), 150),
            'subtitle' => $this->cleanText((string) ($section['subtitle'] ?? 'Clear answers to common questions.'), 260),
            'items' => array_values(array_map(fn ($item) => [
                'question' => $this->cleanText((string) ($item['question'] ?? 'How quickly can we get started?'), 160),
                'answer' => $this->cleanText((string) ($item['answer'] ?? 'You can onboard and configure your workspace in under 10 minutes.'), 450),
            ], array_slice($items, 0, 8))),
        ];
    }

    private function normalizeCta(array $section): array
    {
        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'headline' => $this->cleanText((string) ($section['headline'] ?? 'Ready to Transform Your Workflow?'), 160),
            'subheadline' => $this->cleanText((string) ($section['subheadline'] ?? 'Launch your next initiative today with full control and zero friction.'), 300),
            'button_text' => $this->cleanText((string) ($section['button_text'] ?? 'Get Started Now'), 60),
            'button_url' => $this->sanitizeUrl((string) ($section['button_url'] ?? '#hero'), '#hero'),
        ];
    }

    private function normalizeFooter(array $section, string $brand): array
    {
        $links = is_array($section['links'] ?? null) ? $section['links'] : [
            ['label' => 'Features', 'url' => '#features'],
            ['label' => 'Pricing', 'url' => '#pricing'],
            ['label' => 'FAQ', 'url' => '#faq'],
        ];

        return [
            'visible' => (bool) ($section['visible'] ?? true),
            'brand_name' => $this->cleanText((string) ($section['brand_name'] ?? $brand), 100),
            'tagline' => $this->cleanText((string) ($section['tagline'] ?? 'Built with LandingFlow AI.'), 200),
            'copyright_text' => $this->cleanText((string) ($section['copyright_text'] ?? sprintf('© %s %s. All rights reserved.', date('Y'), $brand)), 160),
            'links' => array_values(array_map(fn ($link) => [
                'label' => $this->cleanText((string) ($link['label'] ?? 'Link'), 50),
                'url' => $this->sanitizeUrl((string) ($link['url'] ?? '#'), '#'),
            ], array_slice($links, 0, 6))),
        ];
    }
}
